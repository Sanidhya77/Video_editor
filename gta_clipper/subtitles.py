"""Subtitle generation (ASS hardsubs and SRT) with customizable style presets and safe-zone margins.
"""

from __future__ import annotations
import math
from pathlib import Path
from typing import List, Dict, Any, Optional

from .audio import AudioSegment
from .style import StylePreset


def build_ass_header(style: Optional[StylePreset] = None) -> str:
    """Builds an ASS script header customized by the chosen StylePreset."""
    font = style.font_name if style else "Arial Black"
    font_size = style.font_size if style else 68
    primary = style.primary_color if style else "&H0000FFFF"
    secondary = style.secondary_color if style else "&H0000FFFF"
    outline = style.outline_color if style else "&H00000000"
    outline_w = style.outline_width if style else 4.5
    shadow_d = style.shadow_depth if style else 2.0
    alignment = style.alignment if style else 2
    margin_v = style.margin_v if style else 380
    margin_h = style.margin_h if style else 60

    hook_size = style.hook_font_size if style else 72
    hook_color = style.hook_color if style else "&H0000FFFF"

    return f"""[Script Info]
; Script generated by GTA VI Clipper
Title: GTA VI Short Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: 1080
PlayResY: 1920

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font},{font_size},{primary},{secondary},{outline},&H80000000,-1,0,0,0,100,100,0,0,1,{outline_w:.1f},{shadow_d:.1f},{alignment},{margin_h},{margin_h},{margin_v},1
Style: HookBanner,{font},{hook_size},{hook_color},&H000000FF,&H00000000,&H80000000,-1,0,0,0,100,100,0,0,8,4.0,2.0,8,60,60,200,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def _format_ass_time(seconds: float) -> str:
    """Formats float seconds into ASS timestamp: H:MM:SS.cs (centiseconds)."""
    seconds = max(0.0, seconds)
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    s = int(seconds % 60)
    cs = int(round((seconds - int(seconds)) * 100))
    if cs >= 100:
        cs = 99
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _format_srt_time(seconds: float) -> str:
    """Formats float seconds into SRT timestamp: HH:MM:SS,mmm (milliseconds)."""
    seconds = max(0.0, seconds)
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    s = int(seconds % 60)
    ms = int(round((seconds - int(seconds)) * 1000))
    if ms >= 1000:
        ms = 999
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _split_into_max_two_lines(text: str, max_chars_per_line: int = 24) -> str:
    """Splits a phrase into at most two balanced lines."""
    words = text.strip().split()
    if not words:
        return ""
    if len(text) <= max_chars_per_line or len(words) <= 3:
        return text

    mid = len(words) // 2
    line1 = " ".join(words[:mid])
    line2 = " ".join(words[mid:])
    return f"{line1}\\N{line2}"


def generate_subtitles_for_clip(
    transcript_segments: List[AudioSegment],
    clip_start: float,
    clip_end: float,
    ass_path: Path,
    srt_path: Path,
    hook_text: Optional[str] = None,
    hook_duration: float = 3.5,
    style: Optional[StylePreset] = None,
) -> bool:
    """Filters transcript segments to clip time, normalizes to 0.0s, and writes ASS and SRT."""
    ass_events = []
    srt_blocks = []
    srt_index = 1

    # Optional top hook banner
    show_hook = (style.hook_style != "none") if style else True
    hook_dur = style.hook_duration if style else hook_duration

    if show_hook and hook_text and hook_text.strip():
        banner_end = min(clip_end - clip_start, hook_dur)
        if banner_end > 0.5:
            start_str = _format_ass_time(0.0)
            end_str = _format_ass_time(banner_end)
            hook_display = _split_into_max_two_lines(hook_text.upper(), max_chars_per_line=20)
            ass_events.append(f"Dialogue: 1,{start_str},{end_str},HookBanner,,0,0,0,,{hook_display}")

    # Process speech segments falling within [clip_start, clip_end]
    for seg in transcript_segments:
        s = max(clip_start, seg.start)
        e = min(clip_end, seg.end)

        if e - s >= 0.2:  # Minimum 200ms
            rel_start = s - clip_start
            rel_end = e - clip_start

            raw_text = seg.text.strip()
            if not raw_text:
                continue

            # Check if timed word highlighting is enabled and tokens/words are available
            tok_source = seg.tokens or seg.words
            use_timed_words = (style and style.highlight_mode == "timed_word" and tok_source)
            if use_timed_words:
                # Generate ASS karaoke tags {\k<centiseconds>} per word
                k_words = []
                for tok in tok_source:
                    tok_text = tok.get("text", "") or tok.get("word", "")
                    tok_dur_cs = int(round(tok.get("duration", 0.3) * 100))
                    k_words.append(f"{{\\k{max(10, tok_dur_cs)}}}{tok_text} ")
                ass_text = "".join(k_words).strip()
                srt_text = raw_text
            else:
                ass_text = _split_into_max_two_lines(raw_text, max_chars_per_line=24)
                srt_text = ass_text.replace("\\N", "\n")

            ass_events.append(
                f"Dialogue: 0,{_format_ass_time(rel_start)},{_format_ass_time(rel_end)},Default,,0,0,0,,{ass_text}"
            )

            srt_blocks.append(
                f"{srt_index}\n{_format_srt_time(rel_start)} --> {_format_srt_time(rel_end)}\n{srt_text}\n"
            )
            srt_index += 1

    # Write ASS file
    ass_path.parent.mkdir(parents=True, exist_ok=True)
    with open(ass_path, "w", encoding="utf-8") as f:
        f.write(build_ass_header(style))
        for ev in ass_events:
            f.write(ev + "\n")

    # Write SRT file
    srt_path.parent.mkdir(parents=True, exist_ok=True)
    with open(srt_path, "w", encoding="utf-8") as f:
        f.write("\n".join(srt_blocks) + "\n")

    return len(ass_events) > 0


def recompute_subtitles_for_trimmed_clip(
    clip_dict: Dict[str, Any],
    all_transcript_segments: List[AudioSegment],
    ass_path: Path,
    srt_path: Path,
    style: Optional[StylePreset] = None,
) -> List[AudioSegment]:
    """Recomputes caption timings relative to trimmed clip in/out boundaries."""
    start_t = float(clip_dict["start_time"])
    end_t = float(clip_dict["end_time"])
    hook_t = clip_dict.get("hook_text")

    generate_subtitles_for_clip(
        transcript_segments=all_transcript_segments,
        clip_start=start_t,
        clip_end=end_t,
        ass_path=ass_path,
        srt_path=srt_path,
        hook_text=hook_t,
        style=style,
    )

    matching_segs = [
        s for s in all_transcript_segments
        if max(start_t, s.start) <= min(end_t, s.end) and min(end_t, s.end) - max(start_t, s.start) >= 0.2
    ]
    return matching_segs
